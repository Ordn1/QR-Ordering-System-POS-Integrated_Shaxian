FEATURED: frozenset[str] = frozenset({"Wonton", "Peanut Butter Noodles", "Braised Pork Set"})


async def seed_menu(session: AsyncSession) -> dict[str, MenuItem]:
    categories: dict[str, Category] = {}
    for order, (name_en, name_fil, name_bis) in enumerate(CATEGORIES, start=1):
        category = Category(
            name_en=name_en,
            name_fil=name_fil,
            name_bis=name_bis,
            display_order=order,
        )
        session.add(category)
        categories[name_en] = category
    await session.flush()

    items: dict[str, MenuItem] = {}
    for (
        category_name,
        name_en,
        name_fil,
        name_bis,
        description_en,
        description_fil,
        description_bis,
        price,
        calories,
        allergens,
        dietary_flags,
        image_filename,
    ) in ITEMS:
        item = MenuItem(
            cat_id=categories[category_name].cat_id,
            name_en=name_en,
            name_fil=name_fil,
            name_bis=name_bis,
            description_en=description_en,
            description_fil=description_fil,
            description_bis=description_bis,
            price=price,
            calories=calories,
            allergens=allergens,
            dietary_flags=dietary_flags,
            image_filename=image_filename,
            is_featured=name_en in FEATURED,
        )
        session.add(item)
        items[name_en] = item
    await session.flush()

    return items